const CATALOG_NAMES = new Set([
  ...semanticRoles.flatMap((role) => [role.name, role.textName]),
  ...supportingAppearance.map((item) => item.name),
]);

export function findScreenColors(source) {
  const findings = [];
  const text = source.replace(/\/\*[\s\S]*?\*\//g, " ");
  for (const match of text.matchAll(
    /#(?:[0-9a-fA-F]{8}|[0-9a-fA-F]{6}|[0-9a-fA-F]{4}|[0-9a-fA-F]{3})\b/g,
  )) {
    findings.push({ kind: "hex", text: match[0] });
  }
  for (const match of text.matchAll(
    /\b(rgba?|hsla?|hwb|lab|lch|oklab|oklch|color)\([^)]*\)/gi,
  )) {
    findings.push({ kind: "function", text: match[0] });
  }
  const masked = text
    .replace(/var\(\s*--[a-zA-Z0-9-]+\s*\)/g, " ")
    .replace(/--[a-zA-Z0-9-]+/g, " ");
  for (const match of masked.matchAll(/\b([a-zA-Z]+)\b/g)) {
    const word = match[1].toLowerCase();
    if (CATALOG_NAMES.has(word)) continue;
    if (NAMED_COLORS.has(word)) {
      findings.push({ kind: "named", text: match[1] });
    }
  }
  return findings;
}
